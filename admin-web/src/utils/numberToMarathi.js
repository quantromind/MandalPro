export function toMarathiDigits(strOrNum) {
  if (strOrNum == null) return '';
  const marathiDigits = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'];
  return String(strOrNum).replace(/[0-9]/g, (d) => marathiDigits[Number(d)]);
}

function convertTwoDigits(n) {
  if (n === 0) return '';
  return MARATHI_NUMBERS[n] || '';
}

function convertThreeDigits(n) {
  let res = '';
  const h = Math.floor(n / 100);
  const rem = n % 100;
  if (h > 0) {
    res += (HUNDREDS_MR[h] || `${MARATHI_NUMBERS[h]} शे`) + ' ';
  }
  if (rem > 0) {
    res += convertTwoDigits(rem) + ' ';
  }
  return res.trim();
}

export function numberToWordsMr(num) {
  const n = parseInt(num, 10);
  if (isNaN(n) || n === 0) return 'शून्य रुपये फक्त';
  if (n < 0) return 'अवैध रक्कम';

  let result = '';

  const crore = Math.floor(n / 10000000);
  const lakh = Math.floor((n % 10000000) / 100000);
  const thousand = Math.floor((n % 100000) / 1000);
  const remainder = n % 1000;

  if (crore > 0) {
    result += (convertTwoDigits(crore) || `${crore}`) + ' कोटी ';
  }
  if (lakh > 0) {
    result += (convertTwoDigits(lakh) || `${lakh}`) + ' लाख ';
  }
  if (thousand > 0) {
    result += (convertTwoDigits(thousand) || `${thousand}`) + ' हजार ';
  }
  if (remainder > 0) {
    result += convertThreeDigits(remainder) + ' ';
  }

  return result.trim() + ' रुपये फक्त';
}
